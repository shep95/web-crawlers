/** Regenerates docs/COVERAGE.md by running the fixture corpus through the real pipeline. */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { analyzeResponse } from "../src/metadata/pipeline.js";
import { CATEGORIES } from "../src/metadata/categories.js";
import { EXTRACTORS } from "../src/metadata/extractors/index.js";
import { fixtureCorpus } from "../tests/fixtures/corpus.js";

const corpus = await fixtureCorpus();
const results = [];
for (const f of corpus) results.push({ name: f.name, rec: await analyzeResponse(f.res, { sourceType: "url", enrich: false }) });
const sym = { observed: "●", not_found_after_inspection: "○", not_applicable: "·", extraction_failed: "✕", unavailable: "⊘" } as const;
const lines: string[] = [];
lines.push("# 41-category coverage matrix", "");
lines.push(`Generated by \`npm run coverage:matrix\` on ${new Date().toISOString().slice(0, 10)} from ${corpus.length} offline fixtures (tests/fixtures). Network-enrichment extractors (DNS, TLS, Wayback, Crossref, GitHub, Hugging Face, package registries, checksum sidecars) are not exercised here; they are verified against live sources after deployment.`, "");
lines.push("Legend: ● found · ○ applicable but not present in this fixture · `·` not applicable to the resource type · ✕ extraction failed", "");
lines.push(`| # | Category | ${results.map((r) => r.name).join(" | ")} | Extractors declaring it | Fields observed |`);
lines.push(`|---|---|${results.map(() => ":-:").join("|")}|---|---|`);
for (const c of CATEGORIES) {
  const cells = results.map((r) => sym[r.rec.categories.find((x) => x.id === c.id)!.state]);
  const extractors = EXTRACTORS.filter((e) => e.categories.includes(c.id)).map((e) => e.id);
  const fields = [...new Set(results.flatMap((r) => r.rec.fields.filter((f) => f.category === c.id).map((f) => f.field)))].slice(0, 12);
  lines.push(`| ${c.id} | ${c.name} | ${cells.join(" | ")} | ${extractors.join(", ") || "pipeline"} | ${fields.join(", ")} |`);
}
lines.push("", "## Per-category status and limitations", "");
lines.push("| # | Category | Status | Supported formats | Limitations |", "|---|---|---|---|---|");
for (const c of CATEGORIES) {
  const hit = results.filter((r) => r.rec.categories.find((x) => x.id === c.id)!.state === "observed").map((r) => r.name);
  lines.push(`| ${c.id} | ${c.name} | ${hit.length ? "Verified (offline fixtures)" : "Implemented, unverified offline"} | ${hit.join(", ") || "—"} | ${c.limitations} |`);
}
// Hand-written sections after this marker (e.g. text intelligence) are kept across regenerations.
const MARKER = "<!-- hand-written sections below are preserved by npm run coverage:matrix -->";
const previous = existsSync("docs/COVERAGE.md") ? readFileSync("docs/COVERAGE.md", "utf8") : "";
const kept = previous.includes(MARKER) ? previous.slice(previous.indexOf(MARKER)) : "";
writeFileSync("docs/COVERAGE.md", lines.join("\n") + "\n" + (kept ? `\n${kept.trimEnd()}\n` : ""));
console.log(`wrote docs/COVERAGE.md (${CATEGORIES.length} categories × ${results.length} fixtures)`);
